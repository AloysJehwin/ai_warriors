// Builds the spec-check circuit (circuits/spec_check.circom), which proves one measured value against its bound, on a public trusted setup:
//   server/zk/spec_check.wasm, server/zk/spec_check.zkey, server/zk/verification_key.json  (the server proves)
//   server/zk/spec_check.ceremony.json   every contribution, so anyone can check the setup
//   src/OrdoSpecVerifier.sol             (OrdoLotResolver verifies each parameter proof on-chain)
//
// Phase 1 is the Privacy & Scaling Explorations Perpetual Powers of Tau (80 contributions, 2^13), not one Ordo made.
// Phase 2 is circuit-specific: the setup is sound if any one contributor destroyed their randomness, so before a
// demo or production each person who should not have to trust the others adds one, and a public beacon closes it.
//
//   node scripts/zk-spec-setup.mjs setup                # compile, phase 2 from the public ptau, first contribution
//   node scripts/zk-spec-setup.mjs contribute "Name"    # one more phase-2 contribution (random entropy, then forgotten)
//   node scripts/zk-spec-setup.mjs beacon <hex>         # final public beacon, e.g. a Hedera or Ethereum block hash
//   node scripts/zk-spec-setup.mjs verify               # check the zkey against the circuit and the public ptau
//
// Needs the circom 2 compiler on PATH (or CIRCOM=/path/to/circom; `npx circom2` also works) for setup and verify. Each
// step regenerates the verifier contract and the key: deploy OrdoSpecVerifier and OrdoLotResolver again after it. Proofs
// already on passports are made again by the server for the new key (it keeps every value and salt).
import { execFileSync } from "node:child_process";
import { createHash, randomBytes } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "..", "server", "zk");
const circom = process.env.CIRCOM ?? "circom";
const snarkjs = join(root, "node_modules", ".bin", "snarkjs");
const PTAU_URL = "https://pse-trusted-setup-ppot.s3.eu-central-1.amazonaws.com/pot28_0080/ppot_0080_13.ptau";
const PTAU_SHA256 = "ccee28086e4b81d81a6e16fdee054d1dbd5276362e2662d4205d31de45cb930f";
const ptauPath = process.env.ORDO_PTAU ?? join(tmpdir(), "ppot_0080_13.ptau");
const zkey = join(out, "spec_check.zkey");
const ceremonyPath = join(out, "spec_check.ceremony.json");

const run = (cmd, args) => execFileSync(cmd, args, { stdio: ["ignore", "pipe", "inherit"], cwd: root }).toString();
const sha256 = (f) => createHash("sha256").update(readFileSync(f)).digest("hex");
const ceremony = () => (existsSync(ceremonyPath) ? JSON.parse(readFileSync(ceremonyPath, "utf8")) : null);

async function ptau() {
  if (!existsSync(ptauPath)) {
    console.log(`downloading ${PTAU_URL}`);
    const res = await fetch(PTAU_URL);
    if (!res.ok) throw new Error(`ptau download failed: HTTP ${res.status}`);
    writeFileSync(ptauPath, Buffer.from(await res.arrayBuffer()));
  }
  if (sha256(ptauPath) !== PTAU_SHA256) throw new Error(`${ptauPath} is not the published PPoT file (sha256 mismatch)`);
  return ptauPath;
}

function compile(work) {
  run(circom, ["circuits/spec_check.circom", "--r1cs", "--wasm", "-o", work]);
  return join(work, "spec_check.r1cs");
}

/** Export the verification key and the verifier contract from the current zkey, and record the step. */
function exportAll(step) {
  const work = mkdtempSync(join(tmpdir(), "ordo-zk-"));
  try {
    run(snarkjs, ["zkey", "export", "verificationkey", zkey, join(out, "verification_key.json")]);
    const sol = join(work, "verifier.sol");
    run(snarkjs, ["zkey", "export", "solidityverifier", zkey, sol]);
    writeFileSync(
      join(root, "src", "OrdoSpecVerifier.sol"),
      `// Generated by scripts/zk-spec-setup.mjs from circuits/spec_check.circom. Do not edit.\n` +
        `// Public signals: [subject, target, op, commitment]. See server/src/core/spec-proofs.ts.\n` +
        readFileSync(sol, "utf8").replace("contract Groth16Verifier", "contract OrdoSpecVerifier"),
    );
    const c = ceremony() ?? { circuit: "spec_check", phase1: { url: PTAU_URL, sha256: PTAU_SHA256, note: "PSE Perpetual Powers of Tau, 80 contributions" }, steps: [] };
    c.steps.push({ ...step, at: new Date().toISOString(), zkeySha256: sha256(zkey) });
    c.verificationKeySha256 = sha256(join(out, "verification_key.json"));
    c.final = step.kind === "beacon";
    writeFileSync(ceremonyPath, `${JSON.stringify(c, null, 2)}\n`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

function contribute(name) {
  if (ceremony()?.final) throw new Error("The ceremony is closed by a beacon; run setup again to start over");
  const next = `${zkey}.next`;
  // the entropy lives only in this process and is never written down
  run(snarkjs, ["zkey", "contribute", zkey, next, `--name=${name}`, `-e=${randomBytes(64).toString("hex")}`]);
  renameSync(next, zkey);
  exportAll({ kind: "contribution", name });
}

const [cmd = "setup", arg] = process.argv.slice(2);
mkdirSync(out, { recursive: true });
if (cmd === "setup") {
  const work = mkdtempSync(join(tmpdir(), "ordo-zk-"));
  try {
    const r1cs = compile(work);
    rmSync(ceremonyPath, { force: true });
    run(snarkjs, ["groth16", "setup", r1cs, await ptau(), zkey]);
    copyFileSync(join(work, "spec_check_js", "spec_check.wasm"), join(out, "spec_check.wasm"));
    contribute(arg ?? process.env.ZK_CONTRIBUTOR ?? "ordo");
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
} else if (cmd === "contribute") {
  if (!arg) throw new Error('Name the contributor: contribute "Your name"');
  contribute(arg);
} else if (cmd === "beacon") {
  if (!/^(0x)?[0-9a-fA-F]{64}$/.test(arg ?? "")) throw new Error("beacon takes a 32-byte hex value that nobody could know in advance, e.g. a future block hash");
  const next = `${zkey}.next`;
  run(snarkjs, ["zkey", "beacon", zkey, next, arg.replace(/^0x/, ""), "10", "-n=public beacon"]);
  renameSync(next, zkey);
  exportAll({ kind: "beacon", value: arg, iterationsExp: 10 });
} else if (cmd === "verify") {
  const work = mkdtempSync(join(tmpdir(), "ordo-zk-"));
  try {
    console.log(run(snarkjs, ["zkey", "verify", compile(work), await ptau(), zkey]));
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
} else throw new Error(`unknown command ${cmd}`);
console.log(`✔ ${cmd}: ${ceremonyPath}`);
