// Compiles contracts with the npm-packaged solc (no compiler download needed).
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
// Contracts for 0G (OrdoAgentNFT) use OpenZeppelin's ERC-721, which needs Cancun; they compile separately and are
// tested on anvil. Everything else stays on Shanghai so the in-process test chain (ganache) can run it.
const CANCUN = new Set(["src/OrdoAgentNFT.sol"]);
// shared sources the Cancun contracts import; they compile in both passes
const SHARED = new Set(["src/OrdoSigned.sol"]);
const sources = {};
const cancunSources = {};
for (const dir of ["src", "test"])
  for (const f of readdirSync(join(root, dir)).filter((f) => f.endsWith(".sol"))) {
    const src = { content: readFileSync(join(root, dir, f), "utf8") };
    (CANCUN.has(`${dir}/${f}`) ? cancunSources : sources)[`${dir}/${f}`] = src;
    if (SHARED.has(`${dir}/${f}`)) cancunSources[`${dir}/${f}`] = src;
  }

const input = {
  language: "Solidity",
  sources,
  settings: {
    // Hedera's EVM supports Cancun; "shanghai" keeps the bytecode runnable on the in-process test chain too.
    evmVersion: "shanghai",
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object", "metadata"] } },
  },
};
const findImports = (path) => {
  try {
    return { contents: readFileSync(require.resolve(path), "utf8") };
  } catch {
    return { error: `File not found: ${path}` };
  }
};
const compile = (i) => {
  const o = JSON.parse(solc.compile(JSON.stringify(i), { import: findImports }));
  for (const e of o.errors ?? []) console[e.severity === "error" ? "error" : "warn"](e.formattedMessage);
  if ((o.errors ?? []).some((e) => e.severity === "error")) process.exit(1);
  return o.contracts;
};
const out = { contracts: { ...compile(input), ...compile({ ...input, sources: cancunSources, settings: { ...input.settings, evmVersion: "cancun" } }) } };

mkdirSync(join(root, "artifacts"), { recursive: true });
for (const [file, contracts] of Object.entries(out.contracts))
  for (const [name, c] of Object.entries(contracts)) {
    writeFileSync(join(root, "artifacts", `${name}.json`), JSON.stringify({ contractName: name, sourceName: file, abi: c.abi, bytecode: `0x${c.evm.bytecode.object}` }, null, 2));
  }
console.log(`compiled with solc ${solc.version()} → artifacts/`);

// The server talks to Ordo's contracts: keep their ABIs in the server package (no cross-package import at runtime).
const art = (n) => JSON.parse(readFileSync(join(root, "artifacts", `${n}.json`), "utf8"));
const trust = art("OrdoTrust");
writeFileSync(
  join(root, "..", "server", "src", "chain", "ordo-trust-abi.ts"),
  `// Generated by contracts/scripts/compile.mjs from OrdoTrust.sol. Do not edit.\nexport const ORDO_TRUST_ABI = ${JSON.stringify(trust.abi)} as const;\nexport const ORDO_TRUST_BYTECODE = "${trust.bytecode}" as const;\n`,
);
const [orders, policies] = [art("OrdoWorkOrders"), art("OrdoPolicies")];
writeFileSync(
  join(root, "..", "server", "src", "chain", "ordo-contracts-abi.ts"),
  `// Generated by contracts/scripts/compile.mjs from OrdoWorkOrders.sol and OrdoPolicies.sol. Do not edit.
export const ORDO_WORK_ORDERS_ABI = ${JSON.stringify(orders.abi)} as const;
export const ORDO_WORK_ORDERS_BYTECODE = "${orders.bytecode}" as const;
export const ORDO_POLICIES_ABI = ${JSON.stringify(policies.abi)} as const;
export const ORDO_POLICIES_BYTECODE = "${policies.bytecode}" as const;
`,
);
const agents = art("OrdoAgentNFT");
writeFileSync(
  join(root, "..", "server", "src", "chain", "ordo-agent-nft-abi.ts"),
  `// Generated by contracts/scripts/compile.mjs from OrdoAgentNFT.sol. Do not edit.
export const ORDO_AGENT_NFT_ABI = ${JSON.stringify(agents.abi)} as const;
export const ORDO_AGENT_NFT_BYTECODE = "${agents.bytecode}" as const;
`,
);
