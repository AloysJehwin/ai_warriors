// Builds the spec-check circuit (circuits/spec_check.circom) into what Ordo needs to prove and verify it:
//   server/zk/spec_check.wasm, server/zk/spec_check.zkey, server/zk/verification_key.json  (the server proves)
//   src/OrdoSpecVerifier.sol                                                               (anyone verifies on-chain)
// Needs the circom 2 compiler on PATH (or CIRCOM=/path/to/circom). The trusted setup is a local, single-party
// ceremony, fine for a demo; a production deployment would use a public Powers of Tau and a multi-party phase 2.
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "..", "server", "zk");
const work = mkdtempSync(join(tmpdir(), "ordo-zk-"));
const circom = process.env.CIRCOM ?? "circom";
const snarkjs = join(root, "node_modules", ".bin", "snarkjs");
const run = (cmd, args) => execFileSync(cmd, args, { stdio: ["ignore", "ignore", "inherit"], cwd: root });
const entropy = () => randomBytes(32).toString("hex");

try {
  run(circom, ["circuits/spec_check.circom", "--r1cs", "--wasm", "-o", work]);
  const ptau = (n) => join(work, `pot_${n}.ptau`);
  run(snarkjs, ["powersoftau", "new", "bn128", "11", ptau(0)]);
  run(snarkjs, ["powersoftau", "contribute", ptau(0), ptau(1), "--name=ordo", `-e=${entropy()}`]);
  run(snarkjs, ["powersoftau", "prepare", "phase2", ptau(1), ptau("final")]);
  const zkey0 = join(work, "spec_check_0.zkey");
  run(snarkjs, ["groth16", "setup", join(work, "spec_check.r1cs"), ptau("final"), zkey0]);
  mkdirSync(out, { recursive: true });
  run(snarkjs, ["zkey", "contribute", zkey0, join(out, "spec_check.zkey"), "--name=ordo", `-e=${entropy()}`]);
  run(snarkjs, ["zkey", "export", "verificationkey", join(out, "spec_check.zkey"), join(out, "verification_key.json")]);
  copyFileSync(join(work, "spec_check_js", "spec_check.wasm"), join(out, "spec_check.wasm"));
  const sol = join(work, "verifier.sol");
  run(snarkjs, ["zkey", "export", "solidityverifier", join(out, "spec_check.zkey"), sol]);
  writeFileSync(
    join(root, "src", "OrdoSpecVerifier.sol"),
    `// Generated by scripts/zk-setup.mjs from circuits/spec_check.circom. Do not edit.\n// Public signals: [subject, target, op, commitment]. See server/src/core/spec-proofs.ts.\n` +
      readFileSync(sol, "utf8").replace("contract Groth16Verifier", "contract OrdoSpecVerifier"),
  );
  console.log(`✔ spec-check circuit built into ${out} and src/OrdoSpecVerifier.sol`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
